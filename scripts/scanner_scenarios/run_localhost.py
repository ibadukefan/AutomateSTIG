class ScenarioFailure(RuntimeError):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ScenarioFailure(message)


def object_value(value: Any, label: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ScenarioFailure(f"{label} must be a JSON object")
    return value


def list_value(value: Any, label: str) -> list[Any]:
    if not isinstance(value, list):
        raise ScenarioFailure(f"{label} must be a JSON array")
    return value


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def canonical_json(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")


def safe_loopback_base_url(raw: str) -> str:
    parsed = urllib.parse.urlsplit(raw)
    require(parsed.scheme == "http", "localhost harness requires an http:// URL")
    require(not parsed.username and not parsed.password, "base URL must not contain credentials")
    require(not parsed.query and not parsed.fragment, "base URL cannot contain a query or fragment")
    require(parsed.path in ("", "/"), "base URL must not contain an application path")
    host = parsed.hostname
    require(host is not None, "base URL is missing a host")
    if host.lower() != "localhost":
        try:
            require(ipaddress.ip_address(host).is_loopback, "base URL must resolve explicitly to loopback")
        except ValueError as error:
            raise ScenarioFailure(
                "base URL host must be localhost or a literal loopback IP address"
            ) from error
    else:
        try:
            addresses = {
                item[4][0]
                for item in socket.getaddrinfo(host, parsed.port, type=socket.SOCK_STREAM)
            }
        except socket.gaierror as error:
            raise ScenarioFailure("localhost did not resolve") from error
        require(addresses, "localhost did not resolve to an address")
        require(
            all(ipaddress.ip_address(address).is_loopback for address in addresses),
            "localhost resolved to a non-loopback address",
        )
    require(parsed.port is not None, "base URL must include the GUI listener port")
    return raw.rstrip("/")


@dataclass(frozen=True)
class HttpResult:
    status: int
    headers: dict[str, str]
    body: bytes


class LocalApi:
    def __init__(self, base_url: str, token: str, timeout: float) -> None:
        self.base_url = safe_loopback_base_url(base_url)
        require(len(token) >= 16, "auth token must contain at least 16 characters")
        self.token = token
        self.timeout = timeout

    def request(
        self,
        method: str,
        path: str,
        *,
        body: bytes | None = None,
        headers: dict[str, str] | None = None,
    ) -> HttpResult:
        require(path.startswith("/api/"), f"unsafe API path {path!r}")
        request_headers = {
            "Accept": "application/json",
            "X-Auth-Token": self.token,
        }
        request_headers.update(headers or {})
        request = urllib.request.Request(
            self.base_url + path,
            data=body,
            headers=request_headers,
            method=method,
        )
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                return HttpResult(
                    response.status,
                    {key.lower(): value for key, value in response.headers.items()},
                    response.read(),
                )
        except urllib.error.HTTPError as error:
            return HttpResult(
                error.code,
                {key.lower(): value for key, value in error.headers.items()},
                error.read(),
            )
        except urllib.error.URLError as error:
            raise ScenarioFailure(
                f"could not reach {self.base_url}; start automatestig-gui first: {error.reason}"
            ) from error

    def json_request(
        self,
        method: str,
        path: str,
        *,
        document: Any | None = None,
        expected_status: int = 200,
    ) -> Any:
        body = None
        headers: dict[str, str] = {}
        if document is not None:
            body = json.dumps(document, separators=(",", ":")).encode("utf-8")
            headers["Content-Type"] = "application/json"
        response = self.request(method, path, body=body, headers=headers)
        require(
            response.status == expected_status,
            f"{method} {path} returned HTTP {response.status}, expected {expected_status}: "
            f"{response.body[:1000].decode('utf-8', errors='replace')}",
        )
        try:
            envelope = object_value(json.loads(response.body), f"{method} {path} response")
        except json.JSONDecodeError as error:
            raise ScenarioFailure(f"{method} {path} did not return JSON") from error
        require(envelope.get("success") is True, f"{method} {path} reported failure: {envelope}")
        require(envelope.get("error") is None, f"{method} {path} returned an unexpected error")
        return envelope.get("data")

    def expected_error(self, method: str, path: str, status: int, code: str) -> None:
        response = self.request(method, path)
        require(
            response.status == status,
            f"{method} {path} returned HTTP {response.status}, expected {status}",
        )
        try:
            envelope = object_value(json.loads(response.body), f"{method} {path} error")
        except json.JSONDecodeError as error:
            raise ScenarioFailure(f"{method} {path} error was not JSON") from error
        require(envelope.get("success") is False, f"{method} {path} error claimed success")
        error = object_value(envelope.get("error"), f"{method} {path}.error")
        require(error.get("code") == code, f"{method} {path} returned error code {error.get('code')!r}")


def multipart_body(
    text_fields: dict[str, str], file_field: tuple[str, str, str, bytes]
) -> tuple[str, bytes]:
    boundary = f"automatestig-scenario-{uuid.uuid4().hex}"
    chunks: list[bytes] = []

    def add_line(value: str = "") -> None:
        chunks.append(value.encode("utf-8") + b"\r\n")

    for name, value in text_fields.items():
        add_line(f"--{boundary}")
        add_line(f'Content-Disposition: form-data; name="{name}"')
        add_line()
        add_line(value)
    name, filename, media_type, contents = file_field
    safe_filename = filename.replace('"', "_").replace("\r", "_").replace("\n", "_")
    add_line(f"--{boundary}")
    add_line(
        f'Content-Disposition: form-data; name="{name}"; filename="{safe_filename}"'
    )
    add_line(f"Content-Type: {media_type}")
    add_line()
    chunks.append(contents)
    chunks.append(b"\r\n")
    add_line(f"--{boundary}--")
    return f"multipart/form-data; boundary={boundary}", b"".join(chunks)


def generate_native_evidence(output_dir: Path) -> dict[str, Any]:
    command = [
        "cargo",
        "run",
        "--quiet",
        "-p",
        "automatestig-core",
        "--example",
        "scanner_scenario_evidence",
        "--",
        "--output-dir",
        str(output_dir),
        "--fixtures-root",
        str(REPO / "fixtures"),
        "--fresh-collected-at",
    ]
    try:
        subprocess.run(
            command,
            cwd=REPO,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
    except FileNotFoundError as error:
        raise ScenarioFailure("cargo is required to generate native adapter evidence") from error
    except subprocess.CalledProcessError as error:
        details = (error.stderr or error.stdout or "").strip()
        raise ScenarioFailure(
            "native adapter evidence generation failed"
            + (f": {details[-2000:]}" if details else "")
        ) from error
    manifest_path = output_dir / "manifest.json"
    try:
        manifest = object_value(json.loads(manifest_path.read_bytes()), "evidence manifest")
    except (OSError, json.JSONDecodeError) as error:
        raise ScenarioFailure("native evidence generator did not produce a valid manifest") from error
    require(
        manifest.get("schema") == "automatestig.localhost-native-evidence/v1",
        "native evidence manifest schema is wrong",
    )
    files = list_value(manifest.get("files"), "evidence manifest files")
    require(len(files) == 6, "native generator must produce six ONTAP/FreeBSD envelopes")
    for item_value in files:
        item = object_value(item_value, "evidence manifest item")
        path = output_dir / str(item.get("path", ""))
        require(path.parent == output_dir, "evidence manifest path escaped its output directory")
        contents = path.read_bytes()
        require(sha256_bytes(contents) == item.get("sha256"), f"generated digest mismatch for {path.name}")
        envelope = object_value(json.loads(contents), path.name)
        require(
            envelope.get("schema") == "automatestig-adapter-evidence/v1",
            f"{path.name} is not a native adapter envelope",
        )
        require(
            envelope.get("evidence_sha256") == item.get("evidence_sha256"),
            f"{path.name} evidence digest binding changed",
        )
        require(
            envelope.get("complete") is item.get("complete"),
            f"{path.name} completeness changed",
        )
    return manifest


def evidence_index(manifest: dict[str, Any], root: Path) -> dict[tuple[str, str], Path]:
    result: dict[tuple[str, str], Path] = {}
    for item_value in list_value(manifest.get("files"), "evidence manifest files"):
        item = object_value(item_value, "evidence manifest item")
        key = (str(item.get("profile_id")), str(item.get("case")))
        require(key not in result, f"duplicate generated evidence case {key}")
        result[key] = root / str(item.get("path"))
    return result


def verify_profile_catalog(api: LocalApi) -> None:
    document = object_value(
        api.json_request("GET", "/api/v1/scanner/profiles"), "scanner profile catalog"
    )
    profiles = {
        str(item.get("profile_id")): item
        for item in list_value(document.get("profiles"), "scanner profile catalog profiles")
        if isinstance(item, dict)
    }
    require(
        EXPECTED_PROFILES.keys() <= profiles.keys(),
        "scanner profile catalog is missing an exercised profile",
    )
    for profile_id, expected in EXPECTED_PROFILES.items():
        profile = profiles[profile_id]
        for key, expected_value in expected.items():
            require(
                profile.get(key) == expected_value,
                f"{profile_id} {key} differs: expected {expected_value!r}, "
                f"found {profile.get(key)!r}",
            )
        require(
            profile.get("total_rules") == expected["full_benchmark_rules"],
            f"{profile_id} total_rules does not use the full benchmark denominator",
        )


def upload_disconnected_evidence(api: LocalApi, profile_id: str, path: Path) -> dict[str, Any]:
    contents = path.read_bytes()
    preflight = object_value(
        api.json_request(
            "POST",
            "/api/v1/runs/preflight",
            document={
                "mode": "disconnected",
                "profile_id": profile_id,
                "collection_method": "evidence",
                "pilot_acknowledged": True,
                "input": {
                    "name": path.name,
                    "size": len(contents),
                    "type": "application/json",
                    "sha256": sha256_bytes(contents),
                },
            },
        ),
        "preflight response",
    )
    require(preflight.get("ready") is True, "preflight was not ready")
    token = preflight.get("preflight_token")
    require(isinstance(token, str) and token, "preflight token is missing")
    require(preflight.get("errors") == [], "preflight returned errors")
    operations = list_value(preflight.get("operations"), "preflight operations")
    require(operations, "preflight did not disclose read-only operations")
    require(all(item.get("read_only") is True for item in operations), "preflight exposed a non-read-only operation")

    media_type, body = multipart_body(
        {
            "preflight_token": token,
            "mode": "disconnected",
            "profile_id": profile_id,
            "input_type": "evidence",
        },
        ("evidence", path.name, "application/json", contents),
    )
    response = api.request(
        "POST",
        "/api/v1/runs/evidence",
        body=body,
        headers={"Content-Type": media_type},
    )
    require(
        response.status == 202,
        f"evidence upload returned HTTP {response.status}: "
        f"{response.body[:1000].decode('utf-8', errors='replace')}",
    )
    try:
        api_envelope = object_value(json.loads(response.body), "run response")
    except json.JSONDecodeError as error:
        raise ScenarioFailure("run response was not JSON") from error
    require(api_envelope.get("success") is True, f"run failed: {api_envelope}")
    return object_value(api_envelope.get("data"), "run response data")


def assert_digest_map(value: dict[str, Any], label: str) -> None:
    required = {
        "request_sha256",
        "result_sha256",
        "benchmark_sha256",
        "check_pack_sha256",
        "evaluation_plan_sha256",
        "evidence_sha256",
    }
    require(required.issubset(value), f"{label} is missing digest bindings")
    for key in required:
        require(
            isinstance(value[key], str) and SHA256_RE.fullmatch(value[key]) is not None,
            f"{label}.{key} is not lowercase SHA-256",
        )


def verify_immutable_run(api: LocalApi, submitted: dict[str, Any]) -> dict[str, Any]:
    run_id = submitted.get("id")
    require(isinstance(run_id, str) and run_id, "stored run has no ID")
    first = object_value(api.json_request("GET", f"/api/v1/runs/{run_id}"), "first run read")
    second = object_value(api.json_request("GET", f"/api/v1/runs/{run_id}"), "second run read")
    expected = canonical_json(submitted)
    require(canonical_json(first) == expected, "POST response differs from the immutable stored run")
    require(canonical_json(second) == expected, "repeated GET changed the stored run response")

    listing = object_value(api.json_request("GET", "/api/v1/runs"), "run listing")
    matches = [
        item
        for item in list_value(listing.get("runs"), "run listing runs")
        if isinstance(item, dict) and item.get("id") == run_id
    ]
    require(len(matches) == 1, "run list must contain the stored run exactly once")
    require(canonical_json(matches[0]) == expected, "run-list projection differs from run detail")
    integrity = object_value(first.get("integrity"), "run integrity")
    assert_digest_map(integrity, "run integrity")
    return first


def safe_zip_names(archive: zipfile.ZipFile) -> list[str]:
    names = archive.namelist()
    require(len(names) == len(set(names)), "handoff ZIP contains duplicate entries")
    for name in names:
        path = PurePosixPath(name)
        require(not path.is_absolute() and ".." not in path.parts, f"unsafe ZIP entry {name!r}")
        require(not archive.getinfo(name).flag_bits & 0x1, f"encrypted ZIP entry {name!r} is unsupported")
    return names


def verify_handoff(api: LocalApi, run: dict[str, Any], output_dir: Path) -> dict[str, Any]:
    run_id = str(run["id"])
    handoff_url = run.get("handoff_url")
    require(handoff_url == f"/api/v1/runs/{run_id}/handoff", "handoff URL is not run-bound")
    response = api.request("GET", str(handoff_url))
    require(response.status == 200, f"handoff returned HTTP {response.status}")
    require(
        response.headers.get("content-type", "").split(";", 1)[0] == "application/zip",
        "handoff content type is not application/zip",
    )
    cache_directives = {
        directive.strip().lower()
        for directive in response.headers.get("cache-control", "").split(",")
    }
    require("no-store" in cache_directives, "handoff is missing no-store")
    zip_path = output_dir / f"{run_id}.handoff.zip"
    zip_path.write_bytes(response.body)

    try:
        with zipfile.ZipFile(zip_path) as archive:
            names = safe_zip_names(archive)
            require(set(names) == EXPECTED_HANDOFF_FILES, f"handoff entries differ: {sorted(names)}")
            members = {name: archive.read(name) for name in names}
    except zipfile.BadZipFile as error:
        raise ScenarioFailure("handoff response is not a valid ZIP") from error

    manifest = object_value(json.loads(members["manifest.json"]), "handoff manifest")
    integrity = object_value(json.loads(members["integrity.json"]), "handoff integrity")
    scanner_run = object_value(json.loads(members["scanner-run.json"]), "scanner-run.json")
    reviews = list_value(json.loads(members["sparse-reviews.json"]), "sparse-reviews.json")
    fallback = object_value(json.loads(members["fallback.cklb"]), "fallback.cklb")

    require(manifest.get("schema") == "automatestig.selected-run-handoff.v3", "handoff schema is wrong")
    require(manifest.get("run_id") == run_id, "handoff manifest is bound to another run")
    require(integrity.get("algorithm") == "sha256", "handoff integrity algorithm is not SHA-256")
    require(
        integrity.get("manifest_sha256") == sha256_bytes(members["manifest.json"]),
        "handoff manifest digest mismatch",
    )
    file_digests = object_value(manifest.get("files"), "handoff manifest files")
    require(
        set(file_digests)
        == {
            "scanner-run.json",
            "sparse-reviews.json",
            "fallback.cklb",
            "results.xccdf.xml",
            "evidence-envelope.json",
        },
        "retained-evidence handoff does not bind exactly its five payload files",
    )
    for name, expected in file_digests.items():
        require(SHA256_RE.fullmatch(str(expected)) is not None, f"manifest digest for {name} is invalid")
        require(sha256_bytes(members[name]) == expected, f"handoff payload digest mismatch for {name}")

    bindings = object_value(manifest.get("bindings"), "handoff bindings")
    assert_digest_map(bindings, "handoff bindings")
    require(bindings == run.get("integrity"), "handoff bindings differ from immutable run integrity")
    scope = object_value(manifest.get("scope"), "handoff scope")
    require(scope.get("ownership_safe_sparse_handoff") is True, "handoff is not marked ownership-safe")
    require(
        scope.get("scanner_owned_reviews_included") == len(reviews),
        "handoff scope review count differs from sparse reviews",
    )
    require(
        scope.get("unreviewed_and_non_scanner_rules_excluded")
        == run["result"]["manual_untouched"],
        "handoff scope excluded count differs from reviewed-manual rules",
    )
    evidence_metadata = object_value(manifest.get("evidence"), "handoff evidence metadata")
    require(evidence_metadata.get("state") == "retained", "new run evidence is not retained")
    require(evidence_metadata.get("included") is True, "retained replay evidence was omitted")
    require(
        evidence_metadata.get("sha256") == bindings["evidence_sha256"],
        "handoff evidence metadata digest changed",
    )
    require(evidence_metadata.get("purged_at") is None, "new run evidence claims to be purged")
    require(evidence_metadata.get("purge_reason") is None, "new run evidence has a purge reason")

    require(scanner_run.get("schema") == "automatestig.scanner-run.v2", "scanner artifact schema is wrong")
    require(scanner_run.get("mode") == "disconnected", "handoff contains a connected run")
    require(scanner_run.get("collection_complete") is True, "handoff contains incomplete evidence")
    require("evidence_envelope" not in scanner_run, "scanner artifact duplicated plaintext evidence")
    evidence_reference = object_value(scanner_run.get("evidence"), "scanner evidence reference")
    require(
        evidence_reference.get("evidence_sha256") == bindings["evidence_sha256"],
        "scanner evidence reference digest changed",
    )
    envelope = object_value(
        json.loads(members["evidence-envelope.json"]), "handoff evidence envelope"
    )
    require(
        envelope.get("schema") == "automatestig-adapter-evidence/v1",
        "replay evidence envelope schema is wrong",
    )
    require(envelope.get("complete") is True, "handoff evidence envelope is incomplete")
    require(envelope.get("evidence_sha256") == bindings["evidence_sha256"], "handoff evidence binding changed")
    require(scanner_run.get("reviews") == reviews, "handoff sparse reviews differ from scanner artifact")
    require(len(reviews) == run["result"]["automated_count"], "handoff review count differs from run")

    stigs = list_value(fallback.get("stigs"), "CKLB fallback STIGs")
    require(len(stigs) == 1, "selected-run CKLB must contain exactly one STIG")
    cklb_rules = list_value(object_value(stigs[0], "CKLB STIG").get("rules"), "CKLB rules")
    expected_rules = run["result"]["automated_count"]
    require(len(cklb_rules) == expected_rules, "CKLB is not ownership-safe and sparse")
    require(
        all(
            isinstance(rule, dict) and rule.get("status") != "not_reviewed"
            for rule in cklb_rules
        ),
        "sparse CKLB contains a manual or Not Reviewed row",
    )
    assessed_rules = {
        str(rule.get("rule_id")): str(rule.get("status"))
        for rule in cklb_rules
        if isinstance(rule, dict) and rule.get("status") != "not_reviewed"
    }
    sparse_results = {
        str(review.get("rule_id")): str(review.get("result"))
        for review in reviews
        if isinstance(review, dict)
    }
    require(len(sparse_results) == len(reviews), "sparse review IDs are duplicated")
    require(set(assessed_rules) == set(sparse_results), "CKLB assessed rules differ from sparse reviews")
    result_to_cklb = {
        "pass": "not_a_finding",
        "fail": "open",
        "notapplicable": "not_applicable",
        "not_applicable": "not_applicable",
    }
    for rule_id, result_name in sparse_results.items():
        require(result_name in result_to_cklb, f"unsupported sparse result {result_name!r}")
        require(
            assessed_rules[rule_id] == result_to_cklb[result_name],
            f"CKLB status differs from sparse result for {rule_id}",
        )
    target_data = object_value(fallback.get("target_data"), "CKLB target data")
    require(
        target_data.get("host_name") == run["device_identity"]["hostname"],
        "CKLB hostname differs from the evidence-bound device identity",
    )

    try:
        xccdf = ET.fromstring(members["results.xccdf.xml"])
    except ET.ParseError as error:
        raise ScenarioFailure("results.xccdf.xml is not well-formed XML") from error
    cdf = f"{{{XCCDF_NS}}}"
    sm = f"{{{STIGMAN_NS}}}"
    ast = f"{{{AUTOMATESTIG_XCCDF_NS}}}"
    require(xccdf.tag == f"{cdf}Benchmark", "XCCDF root is not a 1.2 Benchmark")
    require(
        xccdf.get("id") == f"xccdf_mil.disa.stig_benchmark_{manifest['stig_id']}",
        "XCCDF Benchmark id does not map to the exact STIG",
    )
    test_results = xccdf.findall(f"{cdf}TestResult")
    require(len(test_results) == 1, "XCCDF must contain exactly one TestResult")
    test_result = test_results[0]
    require(
        test_result.get("id") == f"xccdf_org.automatestig_testresult_{run_id}",
        "XCCDF TestResult id is not run-bound",
    )
    require(test_result.get("end-time"), "XCCDF TestResult has no end-time")
    target = test_result.find(f"{cdf}target")
    require(
        target is not None and target.text == run["device_identity"]["hostname"],
        "XCCDF target differs from the evidence-bound device identity",
    )
    xccdf_rule_ids = {
        str(rule.get("id"))
        for group in xccdf.findall(f"{cdf}Group")
        for rule in group.findall(f"{cdf}Rule")
    }
    expected_xccdf_ids = {
        f"xccdf_mil.disa.stig_rule_{rule_id}" for rule_id in sparse_results
    }
    require(
        xccdf_rule_ids == expected_xccdf_ids,
        "XCCDF Rule definitions differ from sparse scanner ownership",
    )
    result_map = {
        str(row.get("rule_id")): row
        for row in reviews
        if isinstance(row, dict) and row.get("rule_id")
    }
    xccdf_results = test_result.findall(f"{cdf}rule-result")
    require(len(xccdf_results) == len(reviews), "XCCDF sparse result count is wrong")
    result_to_xccdf = {
        "pass": "pass",
        "fail": "fail",
        "notapplicable": "notapplicable",
    }
    for rule_result in xccdf_results:
        idref = str(rule_result.get("idref"))
        require(
            idref.startswith("xccdf_mil.disa.stig_rule_"),
            "XCCDF rule-result does not use a STIG Manager-compatible Rule idref",
        )
        raw_rule_id = idref.removeprefix("xccdf_mil.disa.stig_rule_")
        require(raw_rule_id in result_map, f"XCCDF result {raw_rule_id} is not scanner-owned")
        review = result_map[raw_rule_id]
        result = rule_result.find(f"{cdf}result")
        require(result is not None, f"XCCDF result {raw_rule_id} has no result value")
        require(
            result.text == result_to_xccdf.get(str(review.get("result"))),
            f"XCCDF result differs from sparse review for {raw_rule_id}",
        )
        require(result.text not in {"notchecked", "error"}, "complete XCCDF owns an unresolved row")
        detail = rule_result.find(f"{cdf}check/{cdf}check-content/{sm}detail")
        comment = rule_result.find(f"{cdf}check/{cdf}check-content/{sm}comment")
        require(
            (detail.text if detail is not None and detail.text is not None else "")
            == str(review.get("detail", "")),
            f"XCCDF detail differs from sparse review for {raw_rule_id}",
        )
        require(
            (comment.text if comment is not None and comment.text is not None else "")
            == str(review.get("comment", "")),
            f"XCCDF comment differs from sparse review for {raw_rule_id}",
        )
        identity = rule_result.find(f"{cdf}metadata/{ast}rule-identity")
        require(identity is not None, f"XCCDF result {raw_rule_id} has no exact rule identity")
        require(
            identity.get("rule-id") == raw_rule_id
            and identity.get("vuln-id") == identity.get("group-id")
            and str(identity.get("vuln-id", "")).startswith("V-")
            and identity.get("ownership") == "scanner-owned-sparse",
            f"XCCDF result {raw_rule_id} has invalid V-/SV- ownership metadata",
        )
    provenance = test_result.find(f"{cdf}metadata/{ast}provenance")
    require(provenance is not None, "XCCDF TestResult has no AutomateSTIG provenance")
    require(
        provenance.get("schema") == "automatestig.xccdf-results.v1"
        and provenance.get("ownership") == "scanner-owned-sparse",
        "XCCDF provenance schema/ownership is wrong",
    )
    provenance_fields = {
        str(field.get("name")): str(field.get("value"))
        for field in provenance.findall(f"{ast}field")
    }
    expected_provenance = {
        "run-id": run_id,
        "profile-id": scanner_run["profile_id"],
        "scanner-version": manifest["scanner_version"],
        "collection-method": scanner_run["collection_method"],
        "request-sha256": bindings["request_sha256"],
        "result-sha256": bindings["result_sha256"],
        "profile-sha256": evidence_reference["profile_sha256"],
        "benchmark-sha256": bindings["benchmark_sha256"],
        "check-pack-sha256": bindings["check_pack_sha256"],
        "evaluation-plan-sha256": bindings["evaluation_plan_sha256"],
        "evidence-sha256": bindings["evidence_sha256"],
        "collection-plan-sha256": evidence_reference["collection_plan_sha256"],
    }
    for name, expected in expected_provenance.items():
        require(
            provenance_fields.get(name) == expected,
            f"XCCDF provenance field {name!r} differs from the immutable handoff",
        )
    for name, value in provenance_fields.items():
        if name.endswith("sha256"):
            require(SHA256_RE.fullmatch(value) is not None, f"XCCDF provenance {name} is invalid")

    unchanged = object_value(api.json_request("GET", f"/api/v1/runs/{run_id}"), "post-handoff run")
    require(canonical_json(unchanged) == canonical_json(run), "downloading a handoff mutated the run")
    return {
        "zip": str(zip_path),
        "zip_sha256": sha256_bytes(response.body),
        "manifest_sha256": integrity["manifest_sha256"],
        "review_count": len(reviews),
        "xccdf_result_count": len(xccdf_results),
    }


def verify_complete_run(
    api: LocalApi,
    profile_id: str,
    evidence: Path,
    automated_count: int,
    manual_untouched: int,
    reviewed_rules: int,
    full_benchmark_rules: int,
    stig_revision: str,
    output_dir: Path,
) -> dict[str, Any]:
    submitted = upload_disconnected_evidence(api, profile_id, evidence)
    run = verify_immutable_run(api, submitted)
    require(run.get("mode") == "disconnected", "complete run mode changed")
    require(run.get("state") == "preview_ready", "complete disconnected run is not preview-ready")
    require(run.get("collection_method") == "evidence", "collection method changed")
    require(run.get("profile", {}).get("id") == profile_id, "profile binding changed")
    require(run.get("profile", {}).get("stig_revision") == stig_revision, "STIG revision changed")
    result = object_value(run.get("result"), "complete run result")
    require(result.get("collection_complete") is True, "complete evidence became incomplete")
    require(result.get("automated_count") == automated_count, "automated review count is wrong")
    require(result.get("manual_untouched") == manual_untouched, "manual untouched count is wrong")
    require(result.get("reviewed_rules") == reviewed_rules, "reviewed subset count is wrong")
    require(
        result.get("full_benchmark_rules") == full_benchmark_rules,
        "full benchmark denominator is wrong",
    )
    require(
        result.get("out_of_scope_untouched") == full_benchmark_rules - reviewed_rules,
        "outside-profile untouched count is wrong",
    )
    expected_coverage = automated_count * 100.0 / full_benchmark_rules
    require(
        abs(float(result.get("executable_coverage_pct")) - expected_coverage) < 1e-9,
        "executable coverage does not use the full benchmark denominator",
    )
    proposed = list_value(result.get("proposed_reviews"), "proposed reviews")
    require(len(proposed) == automated_count, "complete run omitted sparse proposed reviews")
    require(all(row.get("change") == "handoff" for row in proposed), "disconnected reviews are not marked for handoff")
    preview = object_value(run.get("delivery_preview"), "complete delivery preview")
    require(
        object_value(preview.get("counts"), "complete preview counts")
        == {"create": 0, "update": 0, "unchanged": 0, "conflict": 0},
        "disconnected handoff was misrepresented as a direct review write",
    )
    require(preview.get("reviews") == proposed, "delivery preview differs from proposed reviews")
    require(
        preview.get("manual_untouched") == manual_untouched
        and preview.get("out_of_scope_untouched") == full_benchmark_rules - reviewed_rules,
        "delivery preview scope counts are wrong",
    )
    delivery = object_value(run.get("delivery"), "complete run delivery")
    require(delivery.get("state") == "not_started", "disconnected run created a remote delivery")
    require("id" not in delivery and "request_sha256" not in delivery, "disconnected run has a delivery record")
    handoff = verify_handoff(api, run, output_dir)
    snapshot = output_dir / f"{run['id']}.response.json"
    snapshot.write_text(json.dumps(run, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return {"run_id": run["id"], "profile_id": profile_id, "handoff": handoff}


def verify_incomplete_run(
    api: LocalApi,
    profile_id: str,
    evidence: Path,
    *,
    manual_untouched: int,
    reviewed_rules: int,
    full_benchmark_rules: int,
    stig_revision: str,
    output_dir: Path,
) -> dict[str, Any]:
    submitted = upload_disconnected_evidence(api, profile_id, evidence)
    run = verify_immutable_run(api, submitted)
    require(run.get("state") == "incomplete", "transport-failure evidence did not fail closed")
    require(run.get("handoff_url") is None, "incomplete run exposed a handoff")
    require(run.get("profile", {}).get("stig_revision") == stig_revision, "STIG revision changed")
    result = object_value(run.get("result"), "incomplete run result")
    require(result.get("collection_complete") is False, "incomplete run claims complete collection")
    require(result.get("automated_count") == 0, "incomplete run emitted scanner reviews")
    require(result.get("manual_untouched") == manual_untouched, "manual untouched count is wrong")
    require(result.get("reviewed_rules") == reviewed_rules, "reviewed subset count is wrong")
    require(
        result.get("full_benchmark_rules") == full_benchmark_rules,
        "full benchmark denominator is wrong",
    )
    require(
        result.get("out_of_scope_untouched") == full_benchmark_rules - reviewed_rules,
        "outside-profile untouched count is wrong",
    )
    require(list_value(result.get("proposed_reviews"), "incomplete proposed reviews") == [], "incomplete run proposed delivery reviews")
    require(list_value(result.get("collection_errors"), "collection errors"), "incomplete run retained no diagnostic error")
    preview = object_value(run.get("delivery_preview"), "incomplete delivery preview")
    require(list_value(preview.get("reviews"), "incomplete preview reviews") == [], "incomplete delivery preview contains reviews")
    require(
        object_value(preview.get("counts"), "incomplete preview counts")
        == {"create": 0, "update": 0, "unchanged": 0, "conflict": 0},
        "incomplete delivery counts are nonzero",
    )
    require(
        preview.get("manual_untouched") == manual_untouched
        and preview.get("out_of_scope_untouched") == full_benchmark_rules - reviewed_rules,
        "incomplete preview scope counts are wrong",
    )
    delivery = object_value(run.get("delivery"), "incomplete delivery")
    require(delivery.get("state") == "not_started", "incomplete run entered delivery state")
    require("id" not in delivery and "request_sha256" not in delivery, "incomplete run has a delivery record")

    run_id = str(run["id"])
    api.expected_error("POST", f"/api/v1/runs/{run_id}/deliver", 409, "run_not_deliverable")
    api.expected_error("GET", f"/api/v1/runs/{run_id}/handoff", 409, "handoff_not_available")
    snapshot = output_dir / f"{run_id}.response.json"
    snapshot.write_text(json.dumps(run, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return {
        "run_id": run_id,
        "profile_id": profile_id,
        "collection_error_count": len(result["collection_errors"]),
        "sparse_review_count": 0,
        "delivery_record": False,
        "handoff": False,
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--base-url",
        default="http://127.0.0.1:8787",
        help="running GUI origin, including its explicit loopback port",
    )
    parser.add_argument(
        "--auth-token",
        default=os.environ.get("AUTOMATESTIG_AUTH_TOKEN"),
        help="GUI X-Auth-Token value (or set AUTOMATESTIG_AUTH_TOKEN)",
    )
    parser.add_argument(
        "--artifacts-dir",
        type=Path,
        help="retain generated evidence, run snapshots, and handoffs here",
    )
    parser.add_argument(
        "--generate-only",
        action="store_true",
        help="generate and replay-check native evidence without calling localhost",
    )
    parser.add_argument("--timeout", type=float, default=60.0, help="per-request timeout in seconds")
    return parser.parse_args()


def run(args: argparse.Namespace, work_dir: Path) -> dict[str, Any]:
    evidence_dir = work_dir / "native-evidence"
    evidence_dir.mkdir(parents=True, exist_ok=True)
    manifest = generate_native_evidence(evidence_dir)
    if args.generate_only:
        return {
            "generated": len(manifest["files"]),
            "manifest": str(evidence_dir / "manifest.json"),
            "live_api_exercised": False,
        }

    require(bool(args.auth_token), "--auth-token or AUTOMATESTIG_AUTH_TOKEN is required")
    api = LocalApi(args.base_url, args.auth_token, args.timeout)
    status = object_value(api.json_request("GET", "/api/v1/status"), "scanner status")
    require(status.get("ready") is True, "scanner API is not ready")
    require(int(status.get("profile_count", 0)) >= 3, "scanner API is missing bundled profiles")
    verify_profile_catalog(api)

    paths = evidence_index(manifest, evidence_dir)
    complete = [
        verify_complete_run(
            api,
            "freebsd_gpos",
            paths[("freebsd_gpos", "compliant")],
            automated_count=6,
            manual_untouched=24,
            reviewed_rules=30,
            full_benchmark_rules=203,
            stig_revision="V3R3",
            output_dir=work_dir,
        ),
        verify_complete_run(
            api,
            "netapp_ontap9",
            paths[("netapp_ontap9", "compliant")],
            automated_count=15,
            manual_untouched=7,
            reviewed_rules=22,
            full_benchmark_rules=29,
            stig_revision="V2R4",
            output_dir=work_dir,
        ),
    ]
    incomplete = verify_incomplete_run(
        api,
        "netapp_ontap9",
        paths[("netapp_ontap9", "incomplete")],
        manual_untouched=7,
        reviewed_rules=22,
        full_benchmark_rules=29,
        stig_revision="V2R4",
        output_dir=work_dir,
    )
    return {
        "schema": "automatestig.localhost-scenario-result/v1",
        "base_url": safe_loopback_base_url(args.base_url),
        "native_evidence_generated": len(manifest["files"]),
        "complete_handoff_runs": complete,
        "incomplete_fail_closed_run": incomplete,
        "checks": {
            "preflight_and_upload": True,
            "immutable_api_projection": True,
            "handoff_zip_member_hashes": True,
            "handoff_manifest_binding": True,
            "standards_xccdf_sparse_result": True,
            "profile_release_and_full_denominator": True,
            "ownership_safe_sparse_cklb": True,
            "no_direct_review_write_assumption": True,
            "incomplete_has_no_sparse_reviews": True,
            "incomplete_has_no_delivery_record": True,
            "incomplete_has_no_handoff": True,
        },
        "artifacts_dir": str(work_dir),
    }


def main() -> int:
    args = parse_args()
    try:
        if args.artifacts_dir:
            work_dir = args.artifacts_dir.resolve()
            work_dir.mkdir(parents=True, exist_ok=True)
            summary = run(args, work_dir)
            summary["summary_path"] = str(work_dir / "summary.json")
            (work_dir / "summary.json").write_text(
                json.dumps(summary, indent=2, sort_keys=True) + "\n",
                encoding="utf-8",
            )
        else:
            with tempfile.TemporaryDirectory(prefix="automatestig-scanner-scenarios-") as temporary:
                summary = run(args, Path(temporary))
                summary["artifacts_dir"] = None
        print(json.dumps(summary, indent=2, sort_keys=True))
        return 0
    except (ScenarioFailure, OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
        print(f"scanner scenario failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
